/**
  * @brief  This function handles USB Low Priority or CAN RX0 interrupts.
  *         USB CDC 低优先级中断 (PA11/PA12, USB 设备模式)
  *         此中断优先级低于 USART1, 不影响存储侧板通信.
  * @param  None
  * @retval None
  */
void USB_LP_CAN1_RX0_IRQHandler(void)
{
    USB_CDC_ISR();
}

/**
  * @brief  This function handles USB WakeUp interrupt.
  *         USB 唤醒中断 (EXTI Line18), 用于从 suspend 模式恢复.
  * @param  None
  * @retval None
  */
void USBWakeUp_IRQHandler(void)
{
    EXTI_ClearITPendingBit(EXTI_Line18);   /* 清除 USB 唤醒中断挂起位 */
}

